CREATE TABLE roles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(50) NOT NULL,
    description VARCHAR(255),
    CONSTRAINT pk_roles PRIMARY KEY (id),
    CONSTRAINT uk_roles_name UNIQUE (name),
    CONSTRAINT ck_roles_name_not_blank CHECK (btrim(name) <> '')
);

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    first_name VARCHAR(100) NOT NULL,
    last_name VARCHAR(100) NOT NULL,
    email VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_first_name_not_blank CHECK (btrim(first_name) <> ''),
    CONSTRAINT ck_users_last_name_not_blank CHECK (btrim(last_name) <> ''),
    CONSTRAINT ck_users_email_not_blank CHECK (btrim(email) <> ''),
    CONSTRAINT ck_users_password_not_blank CHECK (btrim(password) <> '')
);

CREATE TABLE user_roles (
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    CONSTRAINT pk_user_roles PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id)
        REFERENCES users (id) ON DELETE CASCADE,
    CONSTRAINT fk_user_roles_role FOREIGN KEY (role_id)
        REFERENCES roles (id) ON DELETE CASCADE
);

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(255),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_categories PRIMARY KEY (id),
    CONSTRAINT uk_categories_name UNIQUE (name),
    CONSTRAINT ck_categories_name_not_blank CHECK (btrim(name) <> '')
);


CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    sku VARCHAR(100) NOT NULL,
    name VARCHAR(150) NOT NULL,
    description VARCHAR(500),
    sale_price NUMERIC(19, 2) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    category_id BIGINT NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_products PRIMARY KEY (id),
    CONSTRAINT uk_products_sku UNIQUE (sku),
    CONSTRAINT ck_products_sku_not_blank CHECK (btrim(sku) <> ''),
    CONSTRAINT ck_products_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT ck_products_sale_price_nonnegative CHECK (sale_price >= 0),
    CONSTRAINT fk_products_category FOREIGN KEY (category_id)
        REFERENCES categories (id) ON DELETE RESTRICT
);

CREATE TABLE inventory (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    product_id BIGINT NOT NULL,
    current_stock INTEGER NOT NULL DEFAULT 0,
    minimum_stock INTEGER NOT NULL DEFAULT 0,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_inventory PRIMARY KEY (id),
    CONSTRAINT uk_inventory_product_id UNIQUE (product_id),
    CONSTRAINT ck_inventory_current_stock_nonnegative CHECK (current_stock >= 0),
    CONSTRAINT ck_inventory_minimum_stock_nonnegative CHECK (minimum_stock >= 0),
    CONSTRAINT fk_inventory_product FOREIGN KEY (product_id)
        REFERENCES products (id) ON DELETE RESTRICT
);

CREATE TABLE suppliers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name VARCHAR(255) NOT NULL,
    tax_id VARCHAR(255) NOT NULL,
    contact_name VARCHAR(255),
    email VARCHAR(255),
    phone VARCHAR(255),
    address VARCHAR(255),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_suppliers PRIMARY KEY (id),
    CONSTRAINT uk_suppliers_tax_id UNIQUE (tax_id),
    CONSTRAINT ck_suppliers_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT ck_suppliers_tax_id_not_blank CHECK (btrim(tax_id) <> '')
);

CREATE TABLE customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    document_number VARCHAR(255) NOT NULL,
    first_name VARCHAR(255) NOT NULL,
    last_name VARCHAR(255) NOT NULL,
    email VARCHAR(255),
    phone VARCHAR(255),
    address VARCHAR(255),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_customers PRIMARY KEY (id),
    CONSTRAINT uk_customers_document_number UNIQUE (document_number),
    CONSTRAINT ck_customers_document_number_not_blank CHECK (btrim(document_number) <> ''),
    CONSTRAINT ck_customers_first_name_not_blank CHECK (btrim(first_name) <> ''),
    CONSTRAINT ck_customers_last_name_not_blank CHECK (btrim(last_name) <> '')
);

CREATE TABLE inventory_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    inventory_id BIGINT NOT NULL,
    type VARCHAR(20) NOT NULL,
    quantity INTEGER NOT NULL,
    previous_stock INTEGER NOT NULL,
    resulting_stock INTEGER NOT NULL,
    performed_by_id BIGINT NOT NULL,
    notes VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_inventory_movements PRIMARY KEY (id),
    CONSTRAINT ck_inventory_movements_type CHECK (type IN ('ENTRY', 'EXIT', 'ADJUSTMENT')),
    CONSTRAINT ck_inventory_movements_quantity_positive CHECK (quantity > 0),
    CONSTRAINT ck_inventory_movements_previous_stock_nonnegative CHECK (previous_stock >= 0),
    CONSTRAINT ck_inventory_movements_resulting_stock_nonnegative CHECK (resulting_stock >= 0),
    CONSTRAINT fk_inventory_movements_inventory FOREIGN KEY (inventory_id)
        REFERENCES inventory (id) ON DELETE RESTRICT,
    CONSTRAINT fk_inventory_movements_performed_by FOREIGN KEY (performed_by_id)
        REFERENCES users (id) ON DELETE RESTRICT
);

CREATE TABLE sales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    sale_number VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    customer_id BIGINT,
    seller_id BIGINT NOT NULL,
    total_amount NUMERIC(19, 2) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_sales PRIMARY KEY (id),
    CONSTRAINT uk_sales_sale_number UNIQUE (sale_number),
    CONSTRAINT ck_sales_sale_number_not_blank CHECK (btrim(sale_number) <> ''),
    CONSTRAINT ck_sales_status CHECK (status IN ('PENDING', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_sales_total_amount_nonnegative CHECK (total_amount >= 0),
    CONSTRAINT fk_sales_customer FOREIGN KEY (customer_id)
        REFERENCES customers (id) ON DELETE RESTRICT,
    CONSTRAINT fk_sales_seller FOREIGN KEY (seller_id)
        REFERENCES users (id) ON DELETE RESTRICT
);

CREATE TABLE sale_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    sale_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(19, 2) NOT NULL,
    subtotal NUMERIC(19, 2) NOT NULL,
    CONSTRAINT pk_sale_items PRIMARY KEY (id),
    CONSTRAINT ck_sale_items_quantity_positive CHECK (quantity > 0),
    CONSTRAINT ck_sale_items_unit_price_nonnegative CHECK (unit_price >= 0),
    CONSTRAINT ck_sale_items_subtotal_nonnegative CHECK (subtotal >= 0),
    CONSTRAINT fk_sale_items_sale FOREIGN KEY (sale_id)
        REFERENCES sales (id) ON DELETE RESTRICT,
    CONSTRAINT fk_sale_items_product FOREIGN KEY (product_id)
        REFERENCES products (id) ON DELETE RESTRICT
);

CREATE TABLE stock_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    supplier_id BIGINT NOT NULL,
    received_by_id BIGINT NOT NULL,
    reference_number VARCHAR(255),
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    total_cost NUMERIC(19, 2) NOT NULL,
    notes VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    confirmed_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_stock_entries PRIMARY KEY (id),
    CONSTRAINT uk_stock_entries_supplier_reference UNIQUE (supplier_id, reference_number),
    CONSTRAINT ck_stock_entries_status CHECK (status IN ('DRAFT', 'CONFIRMED', 'CANCELLED')),
    CONSTRAINT ck_stock_entries_total_cost_nonnegative CHECK (total_cost >= 0),
    CONSTRAINT fk_stock_entries_supplier FOREIGN KEY (supplier_id)
        REFERENCES suppliers (id) ON DELETE RESTRICT,
    CONSTRAINT fk_stock_entries_received_by FOREIGN KEY (received_by_id)
        REFERENCES users (id) ON DELETE RESTRICT
);

CREATE TABLE stock_entry_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    stock_entry_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity INTEGER NOT NULL,
    unit_cost NUMERIC(19, 2) NOT NULL,
    subtotal NUMERIC(19, 2) NOT NULL,
    CONSTRAINT pk_stock_entry_items PRIMARY KEY (id),
    CONSTRAINT ck_stock_entry_items_quantity_positive CHECK (quantity > 0),
    CONSTRAINT ck_stock_entry_items_unit_cost_nonnegative CHECK (unit_cost >= 0),
    CONSTRAINT ck_stock_entry_items_subtotal_nonnegative CHECK (subtotal >= 0),
    CONSTRAINT fk_stock_entry_items_stock_entry FOREIGN KEY (stock_entry_id)
        REFERENCES stock_entries (id) ON DELETE RESTRICT,
    CONSTRAINT fk_stock_entry_items_product FOREIGN KEY (product_id)
        REFERENCES products (id) ON DELETE RESTRICT
);

CREATE TABLE stock_exits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    exit_number VARCHAR(20) NOT NULL,
    reason VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    performed_by_id BIGINT NOT NULL,
    notes VARCHAR(255),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    confirmed_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_stock_exits PRIMARY KEY (id),
    CONSTRAINT uk_stock_exits_exit_number UNIQUE (exit_number),
    CONSTRAINT ck_stock_exits_exit_number_not_blank CHECK (btrim(exit_number) <> ''),
    CONSTRAINT ck_stock_exits_reason CHECK (
        reason IN ('DAMAGED', 'LOSS', 'INTERNAL_USE', 'ADJUSTMENT', 'OTHER')
    ),
    CONSTRAINT ck_stock_exits_status CHECK (status IN ('DRAFT', 'CONFIRMED', 'CANCELLED')),
    CONSTRAINT fk_stock_exits_performed_by FOREIGN KEY (performed_by_id)
        REFERENCES users (id) ON DELETE RESTRICT
);

CREATE TABLE stock_exit_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    stock_exit_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity INTEGER NOT NULL,
    CONSTRAINT pk_stock_exit_items PRIMARY KEY (id),
    CONSTRAINT ck_stock_exit_items_quantity_positive CHECK (quantity > 0),
    CONSTRAINT fk_stock_exit_items_stock_exit FOREIGN KEY (stock_exit_id)
        REFERENCES stock_exits (id) ON DELETE RESTRICT,
    CONSTRAINT fk_stock_exit_items_product FOREIGN KEY (product_id)
        REFERENCES products (id) ON DELETE RESTRICT
);

